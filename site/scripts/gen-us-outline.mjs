// One-off generator for site/src/lib/usOutline.ts: the US outline and state
// borders as pre-projected SVG paths, plus each /power hub's position on them.
// The site never loads a map library or a TopoJSON file at runtime.
//
// The inputs are NOT site dependencies. Install them outside the repo and
// point MAP_DEPS at that node_modules, then rerun when a hub is added:
//   npm i --prefix /tmp/mapdeps --ignore-scripts us-atlas@3.0.1 topojson-client@3.1.0 d3-geo@3.1.1
//   MAP_DEPS=/tmp/mapdeps/node_modules node site/scripts/gen-us-outline.mjs
//
// us-atlas (ISC) is derived from the US Census Bureau's cartographic boundary
// files; states-albers-10m is pre-projected with
// geoAlbersUsa().scale(1300).translate([487.5, 305]) into a 975×610 frame,
// and hubs are projected with that same projection.
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const deps = process.env.MAP_DEPS;
if (!deps) throw new Error("set MAP_DEPS to a node_modules holding us-atlas, topojson-client and d3-geo");
const req = createRequire(path.join(deps, "noop.js"));
const topojson = req("topojson-client");
const d3 = req("d3-geo");
const us = JSON.parse(readFileSync(path.join(deps, "us-atlas", "states-albers-10m.json"), "utf8"));

// A hub is a price basket across many grid nodes, not a point: each sits at
// a representative location for its region (the /power table names the region).
const HUBS = {
  ice_pjm_west: { place: "Western PJM (central Pennsylvania)", lat: 40.3, lon: -77.9 },
  ercot_north_da: { place: "Dallas–Fort Worth", lat: 32.8, lon: -97.0 },
  miso_indiana_da: { place: "Indianapolis", lat: 39.8, lon: -86.2 },
  spp_north_da: { place: "Kansas and Nebraska", lat: 39.8, lon: -98.0 },
  caiso_sp15_da: { place: "Southern California", lat: 34.1, lon: -118.0 },
  ice_palo_verde: { place: "Palo Verde, Arizona", lat: 33.4, lon: -112.9 },
  ice_midc: { place: "Mid-Columbia, Washington", lat: 46.6, lon: -119.6 },
  nyiso_west_da: { place: "Western New York", lat: 42.9, lon: -78.6 },
  ice_mass_hub: { place: "Massachusetts", lat: 42.3, lon: -71.8 },
};

// whole pixels: a 975px frame needs no sub-pixel precision, and the paths ship
// inline in the /power HTML
const pathOf = d3.geoPath().digits(0);
const nation = pathOf(topojson.feature(us, us.objects.nation));
const borders = pathOf(topojson.mesh(us, us.objects.states, (a, b) => a !== b));
const project = d3.geoAlbersUsa().scale(1300).translate([487.5, 305]);
const hubs = Object.fromEntries(Object.entries(HUBS).map(([code, h]) => {
  const xy = project([h.lon, h.lat]);
  if (!xy) throw new Error(`${code}: outside the Albers USA frame`);
  return [code, { ...h, x: Math.round(xy[0] * 10) / 10, y: Math.round(xy[1] * 10) / 10 }];
}));

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "usOutline.ts");
writeFileSync(out, `// GENERATED by site/scripts/gen-us-outline.mjs from us-atlas@3.0.1 (US Census
// cartographic boundaries, ISC licence). Do not edit; rerun the script.
export const US_VIEWBOX = "0 0 975 610";
export const US_NATION = ${JSON.stringify(nation)};
export const US_BORDERS = ${JSON.stringify(borders)};
/** Each hub's representative location, projected into US_VIEWBOX. */
export const HUB_POSITIONS: Record<string, { place: string; lat: number; lon: number; x: number; y: number }> = ${JSON.stringify(hubs, null, 2)};
`);
console.log(`wrote ${out}: nation ${nation.length} chars, borders ${borders.length} chars, ${Object.keys(hubs).length} hubs`);
