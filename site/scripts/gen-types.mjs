// pre{build,dev,test}: generate TypeScript types from the published-artifact
// JSON Schemas (review 2026-09-01 B8). The pipeline validates every artifact
// against schemas/<name>.schema.json before it lands in public/data, so these
// types — not the committed sample the JSON import infers from — are the
// contract a page may rely on. Output is gitignored (like public/schemas) and
// rebuilt from the schemas on every build/test run, so it cannot drift.
//
//   schemas/capacity.schema.json -> src/lib/generated/capacity.ts
//                                   export type CapacityArtifact = { ... }
//   src/lib/generated/index.ts   -> re-exports every artifact type plus an
//                                   ArtifactTypes map keyed by schema name
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const SRC = path.resolve("../schemas");
const DST = path.resolve("src/lib/generated");

const pascal = (name) =>
  name.split(/[_-]/).map((s) => s[0].toUpperCase() + s.slice(1)).join("");

rmSync(DST, { recursive: true, force: true });
mkdirSync(DST, { recursive: true });

const names = readdirSync(SRC)
  .filter((f) => f.endsWith(".schema.json"))
  .map((f) => f.replace(/\.schema\.json$/, ""))
  .sort();

const banner = (name) =>
  `/* Generated by scripts/gen-types.mjs from schemas/${name}.schema.json.\n` +
  ` * Do not edit: rerun \`node scripts/gen-types.mjs\` (npm run build/test/dev do). */`;

for (const name of names) {
  const schema = JSON.parse(readFileSync(path.join(SRC, `${name}.schema.json`), "utf8"));
  const typeName = `${pascal(name)}Artifact`;
  // Titles in these schemas are prose ("capacity.json — /capacity …"); drop the
  // root title so the root type takes typeName, and keep nested titles out of
  // the name space so generation never mints types from human sentences.
  // Objects default to CLOSED (additionalProperties: false below) so a
  // generated type lists exactly the declared fields — except a schema object
  // that declares no properties at all (e.g. capacity `basis: {type: object}`),
  // which is a free-form map and stays open as { [k: string]: unknown }.
  const prep = (node) => {
    if (Array.isArray(node)) return node.map(prep);
    if (node && typeof node === "object") {
      const out = {};
      for (const [k, v] of Object.entries(node)) {
        if (k === "title" && typeof v === "string") continue;
        // "properties"/"$defs" hold maps of subschemas keyed by field name —
        // recurse into each value, never treat the map itself as a schema
        out[k] = k === "properties" || k === "$defs" || k === "definitions" || k === "patternProperties"
          ? Object.fromEntries(Object.entries(v).map(([pk, pv]) => [pk, prep(pv)]))
          : prep(v);
      }
      const isObject = out.type === "object" || (Array.isArray(out.type) && out.type.includes("object"));
      if (isObject && !out.properties && !out.patternProperties && out.additionalProperties === undefined) {
        out.additionalProperties = true;
      }
      return out;
    }
    return node;
  };
  const ts = await compile(prep(schema), typeName, {
    bannerComment: banner(name),
    additionalProperties: false,
    unreachableDefinitions: false,
    strictIndexSignatures: false,
    // minItems would mint [T, ...T[]] tuples no hand-written array satisfies
    ignoreMinAndMaxItems: true,
    format: true,
    style: { semi: true, singleQuote: false },
  });
  writeFileSync(path.join(DST, `${name}.ts`), ts);
}

const index =
  `/* Generated by scripts/gen-types.mjs — every artifact type, keyed by schema name. */\n` +
  names.map((n) => `import type { ${pascal(n)}Artifact } from "./${n}";`).join("\n") +
  "\n\n" +
  names.map((n) => `export type { ${pascal(n)}Artifact } from "./${n}";`).join("\n") +
  "\n\nexport type ArtifactTypes = {\n" +
  names.map((n) => `  ${n}: ${pascal(n)}Artifact;`).join("\n") +
  "\n};\n";
writeFileSync(path.join(DST, "index.ts"), index);
console.log(`generated ${names.length} artifact types in src/lib/generated`);
